"""Generate the EBOOT linker script from the original ELF layout.

splat's linker writer targets ROMs, where every configured segment becomes its
own output section and its own `PT_LOAD`.  A PSP EBOOT is not shaped like that:
it is one contiguous module image with exactly two loadable segments, and the
output section names have to match the original (`.text`, `.text.collision`,
`.rodata`, ...) so the rebuilt ELF can be compared with the shipped one byte for
byte.

So the script is generated straight from the original ELF section table plus the
subsegment list splat produced:

* every `PROGBITS` section becomes an output section pinned to its original
  address, listing the objects that fill it in order;
* `.bss` is `NOLOAD`;
* the two `PT_LOAD`s match the original program headers (`r-x` up to `.dtors`,
  `rw-` from `.cplinit` through `.bss`).

Run after splat: `python tools/gen_linker_script.py`.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

import pspelf  # noqa: E402

# Where splat put the sources, and therefore where the objects land.
ASM_DIR = "asm/eboot"
SRC_DIR = "src/eboot"
ASSET_DIR = "assets/eboot"

# `- {start: 0x1bf114, type: bin, name: 'lib_ent'}` - a raw data blob.  Note
# that the name may itself contain a dot (`.linkonce.d`), so it is captured
# rather than assumed to be a bare identifier.
BLOB_SEGMENT = re.compile(
    r"^  - \{start: (0x[0-9A-Fa-f]+), type: bin, name: '([^']+)'\}")

HEADER = """\
/* ==========================================================================
 *  The Sims 2 PSP - linker script for the EBOOT.
 *
 *  GENERATED BY tools/gen_linker_script.py - do not edit.
 *
 *  The EBOOT is linked at base address 0 and relocated to 0x08804000 by the
 *  PSP loader, so every output section is pinned to the exact address the
 *  original used.  PSPLINK produces two loadable segments: read+execute for
 *  the ELF header, code and read-only data, and read+write for the static
 *  constructor table, the tentative-definition block and .bss.
 * ========================================================================== */

PHDRS
{
    code PT_LOAD FLAGS(5);
    data PT_LOAD FLAGS(6);
}

SECTIONS
{
"""


def matched_c_functions() -> set[str]:
    """Functions whose C version has been verified to compile to the exact
    bytes of the original.

    C is developed independently of the build (see tools/verify_c.py) because
    the original was built with CodeWarrior, which psp-gcc cannot reproduce
    instruction for instruction.  A function is only linked from `src/` once it
    has actually been proven to match, so the image stays byte exact.
    """
    path = ROOT / "config/matched_c.txt"
    if not path.exists():
        return set()
    out = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("//")[0].strip()
        if line:
            out.add(line)
    return out


def collect_objects(elf, config_text: str) -> dict[str, list[str]]:
    """Map ELF section name -> object files, in link order.

    A subsegment's type decides where its object lives: `asm` comes from
    `asm/eboot/<name>.s`, `c`/`cpp` from a file in `src/eboot/`, and raw data
    segments become `assets/eboot/<name>.bin` objects.  Data blobs are matched
    back to their ELF section by *file offset*, since splat renames them
    (`.linkonce.d` -> `linkonce.d.bin`).
    """
    def section_at(offset: int):
        for sec in elf.sections:
            if sec.size and sec.offset <= offset < sec.offset + sec.size:
                return sec
        return None

    objects: dict[str, list[str]] = {}
    section: str | None = None
    matched = matched_c_functions()
    for line in config_text.splitlines():
        seg = re.match(r"^  - name: (\S+)", line)
        if seg:
            section = seg.group(1)
            objects.setdefault(section, [])
            continue
        blob = BLOB_SEGMENT.match(line)
        if blob:
            offset = int(blob.group(1), 16)
            owner = section_at(offset)
            if owner is not None:
                objects.setdefault(owner.name, []).append(
                    f"build/{ASSET_DIR}/{blob.group(2)}.o")
            else:
                print(f"warning: blob {blob.group(2)} at {offset:#x} "
                      f"matches no ELF section", file=sys.stderr)
            continue
        sub = re.match(r"^      - \[0x[0-9A-Fa-f]+, (\w+), ([\w/]+)\]", line)
        if sub and section is not None:
            kind, name = sub.groups()
            if kind != "asm":
                objects[section].append(f"build/{SRC_DIR}/{name}.o")
                continue
            # A function moves from `asm/` to `src/` only once its C has been
            # verified to reproduce the original bytes; see matched_c_functions.
            if name in matched:
                objects[section].append(f"build/{SRC_DIR}/{name}.o")
            else:
                objects[section].append(f"build/{ASM_DIR}/{name}.o")
    return objects


def cname(section: str) -> str:
    return section.lstrip(".").replace(".", "_").replace("-", "_")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--elf", default=str(ROOT / "disks/pgs-si2/EBOOT.dec"))
    ap.add_argument("--config", default=str(ROOT / "config/eboot.splat.yaml"))
    ap.add_argument("--out", default=str(ROOT / "build/config/eboot.elf.ld"))
    ns = ap.parse_args()

    elf = pspelf.load(ns.elf)
    objects = collect_objects(elf, Path(ns.config).read_text(encoding="utf-8"))

    # The second loadable segment starts where the original's does.
    rw_start = 0
    for seg in elf.segments:
        if seg["flags"] & 0x2:            # PF_W
            rw_start = seg["vaddr"]
            break

    out: list[str] = [HEADER]
    # PSPLINK splits the module in two: everything from the ELF header through
    # `.dtors` is one read+execute segment (it is all file-backed), and the
    # static constructor table onwards is read+write because `.bss` lives
    # there.  Assigning by address rather than by permission is what reproduces
    # the original headers - `.rodata` and `.data` are in the *executable* half.
    for sec in elf.sections:
        if not (sec.flags & 0x2) or sec.size == 0 or sec.name == ".bss":
            continue
        objs = objects.get(sec.name, [])
        phdr = "data" if sec.addr >= rw_start else "code"
        # `AT(ADDR(.name))` makes the file layout follow the addresses, which
        # is what PSPLINK does: the module image in the file is the address
        # space plus the ELF header, alignment gaps included.  Concatenating
        # the sections instead would silently close the 0x44 bytes of padding
        # between `.rodata` and `.data`.
        out.append(f"    {sec.name} {sec.addr:#010x} : "
                   f"AT(ADDR({sec.name})) SUBALIGN(4)")
        out.append("    {")
        for obj in objs:
            out.append(f"        {obj}(.text*);")
            out.append(f"        {obj}(.rodata*);")
            out.append(f"        {obj}(.data*);")
        out.append(f"        {cname(sec.name)}_START = .;")
        out.append(f"        {cname(sec.name)}_SIZE = SIZEOF({sec.name});")
        # GNU ld takes the program header assignment *after* the block.
        out.append(f"    }} :{phdr}")
        out.append(f"    {cname(sec.name)}_VRAM_END = .;")
        out.append("")

    bss = elf.section(".bss")
    if bss is not None:
        out.append(f"    .bss {bss.addr:#010x} (NOLOAD) :")
        out.append("    {")
        out.append(f"        . = . + {bss.size:#x};")
        out.append("    } :data")
        out.append("    _bss_END = .;")
        out.append("")

    out += [
        "    /DISCARD/ :",
        "    {",
        "        *(.comment);",
        "        *(.note*);",
        "        *(.pdr);",
        "        *(.MIPS.abiflags);",
        "        *(.reginfo);",
        "        *(.eh_frame);",
        "        *(.gnu.attributes);",
        "    }",
        "}",
        "",
    ]

    path = Path(ns.out)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    n_obj = sum(len(v) for v in objects.values())
    print(f"wrote {path} ({len(out)} lines, {n_obj} objects)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
